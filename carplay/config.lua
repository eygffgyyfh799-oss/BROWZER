Config = {}

-- اسم الأمر لفتح الواجهة
Config.Command = 'carplay'

-- زر اختياري لفتح الواجهة (اتركه '' لو ما تبي زر) - اللاعب يقدر يغيره من إعدادات اللعبة
Config.DefaultKey = ''

-- التحكم (تشغيل / إيقاف / تقديم / ترجيع) للسائق فقط؟ الركاب يسمعون بكل الأحوال
Config.DriverOnly = true

-- بعد ما ينزل آخر شخص: الأغنية تظل "شغالة" هالمدة، بعدها CarPlay تنطفي وتحفظ آخر نقطة
-- لو رجعت قبلها تكمل من مكانها الحالي، ولو رجعت بعدها تكمل من النقطة اللي انطفت عندها
Config.OffAfterMinutes = 3

-- بعد ما تنطفي (بعد الـ 3 دقايق) لما يركب السيارة مرة ثانية: يكمل تلقائياً من آخر نقطة؟
Config.ResumeAfterOff = true

-- كم ثانية يقدم / يرجع الزر
Config.SkipSeconds = 10

-- أقصى عدد أغاني في السجل
Config.MaxHistory = 30

-- الصوت الافتراضي (0 - 100)
Config.DefaultVolume = 50

-- ===== الصوت ثلاثي الأبعاد (3D) =====
-- اللي برا السيارة يسمعون الأغنية حسب بعدهم عنها، والصوت يتغير لو الأبواب / الشبابيك مفتوحة
Config.Sound = {
    Enabled3D    = true,  -- false = الصوت لركاب السيارة بس (مثل قبل)
    Range        = 25.0,  -- أبعد مسافة (متر) ينسمع فيها الصوت برا السيارة (تتضاعف مع البوست)
    Rolloff      = 1.6,   -- قوة تلاشي الصوت مع المسافة (أكبر = يخف أسرع)
    ClosedCabin  = 0.35,  -- قوة الصوت برا لو الأبواب والشبابيك مسكرة (0 - 1)
    Occlusion    = 0.6,   -- لو فيه شي حاجز بينك وبين السيارة (جدار / مبنى)
    OtherVehicle = 0.55,  -- لو أنت داخل سيارة ثانية
    MaxStreams   = 3,     -- أقصى عدد سيارات تسمعها بنفس الوقت (الأقرب)
    UpdateMs     = 200,   -- كل كم ملي ثانية يتحدث الصوت (أقل = أنعم وأثقل)
}

-- ===== رفع مستوى الصوت (Boost) =====
-- كل مستوى يضرب الصوت ويوسع مسافة السماع برا السيارة
-- ملاحظة: يوتيوب أعلى شي يوصل 100%، فالبوست يفرق أكثر لما يكون الصوت أقل من الأقصى، وبرا السيارة
Config.BoostLevels = { 1.0, 1.5, 2.0, 3.0 }

-- بعد كم ساعة تنحذف جلسة السيارة المنطفية من ذاكرة السيرفر
Config.ForgetAfterHours = 12

-- كلاسات مركبات ما يشتغل فيها CarPlay (13 = سياكل)
Config.BlacklistedClasses = {
    [13] = true,
}

Config.Locale = {
    not_in_vehicle   = 'لازم تكون داخل سيارة',
    driver_only      = 'التحكم للسائق فقط',
    invalid_link     = 'الرابط غير صحيح',
    resumed          = 'CarPlay: كملنا من آخر نقطة',
    powered_off      = 'CarPlay انطفت وحفظنا آخر نقطة',
    embed_blocked    = 'هذا المقطع صاحبه مانع تشغيله خارج يوتيوب، جرب مقطع ثاني',
    video_error      = 'تعذر تشغيل المقطع',
    open_key         = 'فتح CarPlay',
}

-- غيّر هذي الدالة لإشعار الفريمورك حقك (RespectCore مثلاً)
Config.Notify = function(msg)
    BeginTextCommandThefeedPost('STRING')
    AddTextComponentSubstringPlayerName(msg)
    EndTextCommandThefeedPostTicker(false, true)
end
